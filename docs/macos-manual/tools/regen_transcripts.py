#!/usr/bin/env python3
"""Regenerate the manual's listings and CLI dialogs from sources (Dave 2026-10-19: no listing or
dialog in src/ is typed by hand; BRIEF_to_manual_regen.md).

Two products, both written to src/transcripts/ and pulled into a chapter by a marker line
`<!-- transcript: NAME -->` (tools/include_transcripts.lua):

  listing_<file>.md   an example deck / journal / test file from examples/, VERBATIM, as an
                      indented code block (the appendix is a tutorial: the file as written, not the
                      SAVE-emitted canonical form).  No engine needed.
  <name>.md           a CLI dialog: tools/transcripts/<journal>.jou run on a pty by the CLI suite's
                      driver (cli_tests/cli_cmd_gate.py, the same grammar: # COPY / $TMP / $DECK /
                      # EXPECT / # EXPECT-NOT), printed the way the manual prints a dialog -- the
                      command as a `MACOS\\>**cmd**` line, then the engine's lines (prompts with the
                      answers as the pty saw them) in a 4-space code block, the engine's spacing kept.

Journal directives (comments to the gate, read only here):
  # TRANSCRIPT: <name> [+device]
                        the lines that follow go to src/transcripts/<name>.md (one journal may feed
                        several dialogs; the setup lines before the first TRANSCRIPT are not printed);
                        +device keeps the Graphics device prompt line (where the text is about it)
  # TRANSCRIPT-OFF      the lines that follow are setup again (not printed)
  # TRANSCRIPT-BANNER: <name>
                        the start-up dialog (the banner, the model-size prompt and its answer, up to
                        the first MACOS> prompt) goes to src/transcripts/<name>.md
A journal with no TRANSCRIPT directive prints everything to <journal>.md.

Every journal is a gate: one with no # EXPECT line is refused (a dialog that cannot be pinned is a
finding, not a transcript), and a journal whose run misses an expectation writes NOTHING -- a
transcript cannot rot silently.  `cli_tests/run_cli_tests.sh cmd` runs the same journals on both
compilers.

Removed from the engine's output (and only these): the `Graphics device/type` prompt line with its
answer (as the figure journals answer it, /null) unless the dialog asks for it with +device, the
`Compute time was` line (wall-clock, differs run to run), and the scratch directory's path wherever it
is echoed; the repository root prints as `<macos>` and the home directory as `~` (machine paths).

Usage (from docs/macos-manual):
  python3 tools/regen_transcripts.py [<macos binary>] [--listings-only] [journal names...]
Default binary: the ifx build in the clean worktree ~/dev/macos_cli_base (the manual prints one
engine; the gate runs both).
"""
import glob, os, re, shutil, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAN = HERE.parent
ROOT = MAN.parent.parent
OUT = MAN / "src" / "transcripts"
JOU = HERE / "transcripts"
EXAMPLES = MAN / "examples"
LISTED = ("*.in", "*.jou", "*.test", "*.cmn", "*.f")

sys.path.insert(0, str(ROOT / "cli_tests"))
from cli_cmd_gate import run_journal  # noqa: E402

HEADER = "<!-- GENERATED by tools/regen_transcripts.py from {src} -- do not edit; `make transcripts` -->\n\n"


class Marks(list):
    raw = b""


def code_block(lines):
    body = [("    " + l.rstrip()) if l.strip() else "" for l in lines]
    while body and not body[-1]:
        body.pop()
    while body and not body[0]:
        body.pop(0)
    return "\n".join(body) + "\n"


def listings():
    n = 0
    for pat in LISTED:
        for f in sorted(EXAMPLES.glob(pat)):
            text = f.read_text()
            if re.search(r"[DE][-+]$", text, re.M):
                sys.exit(f"{f.name}: a number ends at the margin ([DE][-+]$) -- a PDF line wrap split it; rejoin it first")
            if "\t" in text:
                sys.exit(f"{f.name}: a TAB (an indented code block would re-space it); expand it in the example first")
            out = OUT / f"listing_{f.name.replace('.', '_')}.md"
            out.write_text(HEADER.format(src=f"examples/{f.name}") + code_block(text.splitlines()))
            n += 1
    print(f"{n} listings from examples/")


def md_escape(s):
    return re.sub(r"([\\`*_\[\]<>#|])", r"\\\1", s)


def parse(path):
    """The journal's lines as the gate sends them (non-# lines), each tagged with the transcript
    it belongs to (None = setup), plus the EXPECT count."""
    sends, target, named, nexp, opts, banner = [], None, False, 0, {}, None
    for l in open(path).read().splitlines():
        if l.startswith("# TRANSCRIPT-OFF"):
            target = None
        elif l.startswith("# TRANSCRIPT-BANNER:"):
            banner, named = l.split(":", 1)[1].strip(), True
        elif l.startswith("# TRANSCRIPT:"):
            toks = l.split(":", 1)[1].split()
            target, named = toks[0], True
            opts[target] = set(toks[1:])
        elif l.startswith("# EXPECT:"):
            nexp += 1
        elif not l.startswith("#"):
            sends.append(target)
    if not named:
        sends = [path.stem] * len(sends)
    return sends, nexp, opts, banner


DEVICE = re.compile(r"^Graphics device/type")
DROP = [re.compile(r"^\s*Compute time was")]


def clean(l, tmp):
    l = l.replace(tmp + os.sep, "").replace(tmp, ".")
    return l.replace(str(ROOT), "<macos>").replace(str(Path.home()), "~")


def dialog(raw, marks, sends, tmp, opts, banner):
    """{name: markdown} -- each top-level command (a line sent at the MACOS> prompt) opens an entry;
    the lines sent at its sub-prompts belong to it."""
    text = raw.decode(errors="replace")
    # byte offsets -> the decoded text: re-decode the prefix at each mark
    offs = [len(raw[:m].decode(errors="replace")) for m in marks] + [len(text)]
    out = {}
    if banner:
        pre = text[:offs[0]].replace("\r", "")
        pre = re.sub(r"\s*MACOS>\s*$", "\n", pre)
        lines = [clean(l, tmp) for l in pre.split("\n")]
        out[banner] = [code_block([l[1:] if l.startswith(" ") else l for l in lines]) + "\nMACOS\\>\n"]
    entry = None   # (name, command, [engine lines])
    entries = []
    for i, name in enumerate(sends):
        seg = text[offs[i]:offs[i + 1]].replace("\r", "")
        top = re.search(r"MACOS>\s*$", text[max(0, offs[i] - 200):offs[i]].replace("\r", ""))
        if top:
            # the prompt was printed before the mark: the segment opens with the command's echo
            m = re.match(r"([^\n]*)\n?", seg)
            entry = [name, m.group(1), []]
            entries.append(entry)
            seg = seg[m.end():]
        elif entry is None:
            sys.exit(f"line {i} answers a sub-prompt before any command")
        # the trailing MACOS> prompt of the next command belongs to the next entry
        seg = re.sub(r"\s*MACOS>\s*$", "\n", seg)
        entry[2].append(seg)
    for name, cmd, segs in entries:
        if name is None:
            continue
        lines = []
        for l in "".join(segs).split("\n"):
            if any(p.search(l) for p in DROP) or (DEVICE.search(l) and "+device" not in opts.get(name, ())):
                continue
            l = clean(l, tmp)
            lines.append(l[1:] if l.startswith(" ") else l)   # Fortran list-directed carriage column
        cmd = clean(cmd, tmp)
        md = f"MACOS\\>**{md_escape(cmd.strip())}**\n"
        body = code_block(lines)
        if body.strip():
            md += "\n" + body
        out.setdefault(name, []).append(md)
    return {k: "\n".join(v) for k, v in out.items()}


def transcripts(binary, only):
    res = os.environ.get("MACOS_RESOURCES", str(ROOT.parent / "MACOS_resources"))
    jous = sorted(JOU.glob("*.jou"))
    if only:
        jous = [j for j in jous if j.stem in only]
    bad = []
    for j in jous:
        sends, nexp, opts, banner = parse(j)
        if nexp == 0:
            bad.append(f"{j.name}: no # EXPECT -- a dialog that cannot be pinned is a finding, not a transcript")
            continue
        tmp = tempfile.mkdtemp(prefix="mtx_", dir="/tmp")    # short: the pty is 80 columns
        try:
            marks = Marks()
            st, missed, txt, dt = run_journal(binary, str(j), str(ROOT), res, tmp, marks)
            if st != "pass":
                bad.append(f"{j.name}: {st} {' | '.join(missed)}")
                continue
            if len(marks) != len(sends):
                bad.append(f"{j.name}: {len(marks)} lines sent, {len(sends)} parsed")
                continue
            for name, md in dialog(marks.raw, marks, sends, tmp, opts, banner).items():
                (OUT / f"{name}.md").write_text(HEADER.format(src=f"tools/transcripts/{j.name}") + md)
                print(f"{name}.md  <- {j.name}  ({dt:.1f} s)")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
    if bad:
        sys.exit("transcript journals refused:\n  " + "\n  ".join(bad))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    binary = args[0] if args and os.path.isfile(args[0]) else str(Path.home() / "dev" / "macos_cli_base" / "build_release" / "bin" / "macos")
    only = args[1:] if args and os.path.isfile(args[0]) else args
    OUT.mkdir(exist_ok=True)
    listings()
    if "--listings-only" not in sys.argv:
        transcripts(binary, only)


if __name__ == "__main__":
    main()
